# ESPDock version stamp — PlatformIO pre-build script.
#
# Runs in every `pio run` (ESPDock, VS Code, CLI) and writes
# $BUILD_DIR/espdock/espdock_build_info.h with project, env, git commit,
# build time and a source hash. The source hash MUST match ESPDock's
# CodeFingerprint (Swift): SHA-256 per tracked file, then SHA-256 over the
# sorted "path:hash" lines joined by "\n". Tracked: platformio.ini and *.csv
# at the root, plus everything under src/, include/, lib/; dot-files and
# dot-folders are skipped.
#
# Only the small ESPDock.cpp includes the generated header, so a changing
# build time recompiles one file, not the whole Arduino core.
Import("env")

import datetime
import hashlib
import os
import subprocess

project_dir = env.subst("$PROJECT_DIR")


def tracked_files():
    files = []
    for name in os.listdir(project_dir):
        path = os.path.join(project_dir, name)
        if os.path.isfile(path) and (name == "platformio.ini" or name.endswith(".csv")):
            files.append(name)
    for top in ("src", "include", "lib"):
        base = os.path.join(project_dir, top)
        for root, dirs, names in os.walk(base):
            dirs[:] = [d for d in dirs if not d.startswith(".")]
            for name in names:
                if name.startswith("."):
                    continue
                rel = os.path.relpath(os.path.join(root, name), project_dir)
                files.append(rel.replace(os.sep, "/"))
    return sorted(files)


def source_hash():
    lines = []
    for rel in tracked_files():
        with open(os.path.join(project_dir, rel), "rb") as fh:
            lines.append("%s:%s" % (rel, hashlib.sha256(fh.read()).hexdigest()))
    return hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()


def git(*args):
    try:
        return subprocess.check_output(["git", "-C", project_dir] + list(args),
                                       stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        return ""


def c_string(value):
    return '"%s"' % value.replace("\\", "\\\\").replace('"', '\\"')


commit = git("rev-parse", "--short", "HEAD")
if commit and git("status", "--porcelain", "--untracked-files=no"):
    commit += "-dirty"

info = {
    "ESPDOCK_PROJECT": os.path.basename(project_dir),
    "ESPDOCK_ENV": env["PIOENV"],
    "ESPDOCK_COMMIT": commit,
    "ESPDOCK_BUILT": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "ESPDOCK_SOURCE": source_hash(),
}

out_dir = os.path.join(env.subst("$BUILD_DIR"), "espdock")
os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, "espdock_build_info.h"), "w") as fh:
    fh.write("// Generated by ESPDock's espdock_version.py — do not edit.\n#pragma once\n")
    for key, value in info.items():
        fh.write("#define %s %s\n" % (key, c_string(value)))
env.Append(CPPPATH=[out_dir])
print("ESPDock: %s %s source=%s" % (info["ESPDOCK_PROJECT"], commit or "(no git)", info["ESPDOCK_SOURCE"][:12]))
